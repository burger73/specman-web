// Modell → Text. Portierung von specman.model.v002.io.ModelSerializer_V002.
// Die Ausgabe muss zeichengleich zum Original sein (Roundtrip-Test), daher auch die Eigenheiten übernommen.
import {
  addStepRecursively,
  normalizeId,
  queryAllSteps,
  type BranchSequence,
  type CaseStep,
  type CatchArea,
  type ChangeInfo,
  type Diagram,
  type EditorContent,
  type IfElseStep,
  type IfStep,
  type ImageArea,
  type ListItemEditArea,
  type MetaTagConfig,
  type SourceStep,
  type Step,
  type StepSequence,
  type SubsequenceStep,
  type TableEditArea,
  type TextEditArea,
} from './model.ts';

const COMMENT_INTRO = '//';
export const MODEL_TYPE = 'specman.model.v002.DiagramModel_V002';
/** Version, die beim Schreiben ins Envelope kommt, solange keine andere angegeben ist */
export const SPECMAN_VERSION = '1.4.0';

type IdToNum = Map<string, string>;

/** Serializes a Diagram to SpecmanModel_V002 text format. */
export function writeDiagram(model: Diagram, specmanVersion: string = SPECMAN_VERSION): string {
  return new Serializer().serialize(model, specmanVersion);
}

/** Schritte als Fragment (Zwischenablage) */
export function writeSteps(steps: Step[]): string {
  return new Serializer().serializeSteps(steps);
}

/** Tabelle als Fragment (Zwischenablage) */
export function writeTable(table: TableEditArea): string {
  return new Serializer().serializeTable(table);
}

class Serializer {
  private sb = '';
  private indentionLevel = 0;

  private indent(): string {
    return '    '.repeat(this.indentionLevel);
  }

  serializeSteps(steps: Step[]): string {
    this.sb = '';
    this.indentionLevel = 0;
    const all: Step[] = [];
    for (const s of steps) addStepRecursively(s, all);
    const idToNum: IdToNum = new Map();
    for (const s of all) idToNum.set(s.id, s.stepNumber);
    for (const s of steps) this.appendStep(s, idToNum);
    return this.sb;
  }

  serializeTable(table: TableEditArea): string {
    this.sb = '';
    this.indentionLevel = 0;
    this.appendTable(table);
    return this.sb;
  }

  serialize(model: Diagram, specmanVersion: string): string {
    const idToStepNumber: IdToNum = new Map();
    for (const s of queryAllSteps(model)) idToStepNumber.set(s.id, s.stepNumber);
    this.sb = '';
    this.indentionLevel = 0;
    const c = COMMENT_INTRO;
    this.sb += `${c} {"specmanVersion":"${specmanVersion}","modelType":"${MODEL_TYPE}"}\n`;
    this.sb += `${c} Specman: ${model.name ?? ''}\n`;
    this.sb += `${c} Format defined by grammar: SpecmanModel_V002.g4\n`;
    this.sb += `${c} Step numbers (first parameter of each step): unique diagram-wide; referenced by catch blocks and step links in text; sanitizer renumbers consistently\n`;
    this.sb += `${c} plain=\`...\` fields: plain-text rendition, regenerated by Specman on every sanitize run\n`;
    this.sb += `${c} markups=[...] fields: change-tracking annotations, maintained by Specman\n`;
    this.sb += `${c} image(..., type=png) { [base64:...] } blocks: embedded binary image data (base64-encoded)\n`;
    this.sb += `${c} image(..., type=plantuml) { \`...\` } blocks: PlantUML source of a diagram, Specman renders the picture from it\n`;
    this.sb += `${c} backup=(changeset, \`...\`) in a plantuml image: source from before that change set changed it, maintained by Specman, leave it alone\n`;
    this.appendSettings(model);
    if (hasContent(model.intro)) {
      this.sb += '\n';
      this.blockOpen('intro', this.editContainerHead(model.intro));
      this.appendEditContainerTail(model.intro, 1);
      this.blockClose();
    }
    this.sb += '\n';
    this.blockOpen('mainSequence');
    this.appendSteps(model.mainSequence, idToStepNumber);
    this.appendCatchArea(model.mainSequence?.catchArea, idToStepNumber);
    this.blockClose();
    if (hasContent(model.outro)) {
      this.sb += '\n';
      this.blockOpen('outro', this.editContainerHead(model.outro));
      this.appendEditContainerTail(model.outro, 1);
      this.blockClose();
    }
    return this.sb;
  }

  // ---- Settings ----

  private line(text: string): void {
    this.sb += this.indent() + text + '\n';
  }

  private appendSettings(model: Diagram): void {
    this.sb += '\n';
    this.blockOpen('settings');
    this.line(`width=${model.width}`);
    this.line(`zoom=${model.zoomFactor}`);
    this.line(`changeModeEnabled=${model.changeModeEnabled}`);
    this.line(`changeSetName=${model.changeSetName ?? 'yellow'}`);
    const pdf = model.pdfExportOptions;
    if (pdf) {
      this.blockOpen('pdfOptions');
      if (pdf.filename !== undefined) this.line(`filename=\`${pdf.filename}\``);
      if (pdf.modelFilename !== undefined) this.line(`modelFilename=\`${pdf.modelFilename}\``);
      if (pdf.pageSize !== undefined) this.line(`pageSize=${pdf.pageSize}`);
      this.line(`portrait=${pdf.portrait}`);
      this.line(`paging=${pdf.paging}`);
      this.blockClose();
    }
    if (model.metaTagConfigs.length > 0) {
      this.blockOpen('metaTags');
      for (const config of model.metaTagConfigs) this.appendMetaTagConfig(config);
      this.blockClose();
    }
    this.blockClose();
  }

  private appendMetaTagConfig(config: MetaTagConfig): void {
    const border = config.borderColor !== undefined ? `border=${toModelColor(config.borderColor)}` : undefined;
    // The label may only be omitted if there is an icon instead, see the grammar.
    const label = config.label === '' && config.iconSvg !== undefined ? undefined : `label=\`${escapeBackticks(config.label)}\``;
    // A backtick in the SVG is replaced by an XML character reference, which keeps the SVG valid.
    const icon = config.iconSvg !== undefined ? `icon=\`${config.iconSvg.replaceAll('`', BACKTICK_CHARACTER_REFERENCE)}\`` : undefined;
    const freetext = config.freetextAllowed ? undefined : 'freetext=false';
    this.blockBegin(
      'tag',
      '`' + escapeBackticks(config.name) + '`',
      `background=${toModelColor(config.backgroundColor)}`,
      border,
      label,
      icon,
      freetext,
    );
    this.sb += '\n';
  }

  // ---- htmlContent: `html`, plain=`...`, markups=[...] ----

  private htmlContent(area: TextEditArea): string {
    let hb = '`' + escapeBackticks(extractBodyHtml(area.text)) + '`';
    if (area.plainText) {
      // Models converted from V1 may still carry the invisible leading newline in their plain text
      hb += ', plain=`' + escapeBackticks(area.plainText.replace(/^\n/, '')) + '`';
    }
    if (area.markups.length > 0) {
      hb += ', markups=[';
      for (const m of area.markups) {
        hb += `(${m.from},${m.to},${m.type}`;
        if (m.changeset) hb += ',' + m.changeset;
        hb += ')';
      }
      hb += ']';
    }
    return hb;
  }

  private editContainerHead(container: EditorContent | undefined): string {
    if (!hasContent(container)) return '``';
    const first = container.areas[0];
    return first.kind === 'text' ? this.htmlContent(first) : '``';
  }

  private firstAreaChangeAnno(container: EditorContent): string | undefined {
    const first = container.areas[0];
    return first?.kind === 'text' ? changeAnno(first.changeInfo) : undefined;
  }

  // ---- EditContainer tail: areas[fromIndex..n] in block ----

  private appendEditContainerTail(container: EditorContent | undefined, fromIndex: number): void {
    if (!container) return;
    const areas = container.areas;
    let i = fromIndex;
    while (i < areas.length) {
      const area = areas[i];
      if (area.kind === 'listItem') {
        const ordered = area.ordered;
        this.blockOpen('list', `ordered=${ordered}`);
        let li: (typeof areas)[number];
        while (i < areas.length && (li = areas[i]).kind === 'listItem' && li.ordered === ordered) {
          this.appendListItem(li);
          i++;
        }
        this.blockClose();
      } else if (area.kind === 'text') {
        const anno = changeAnno(area.changeInfo);
        this.sb += this.indent() + 'text(' + this.htmlContent(area);
        if (anno) this.sb += ', ' + anno;
        this.sb += ')\n';
        i++;
      } else if (area.kind === 'table') {
        this.appendTable(area);
        i++;
      } else {
        this.appendImage(area);
        i++;
      }
    }
  }

  private appendListItem(item: ListItemEditArea): void {
    const hasExtraAreas = hasContent(item.content) && item.content.areas.length > 1;
    if (hasExtraAreas) {
      this.blockOpen('item', this.editContainerHead(item.content), changeAnno(item.changeInfo));
      this.appendEditContainerTail(item.content, 1);
      this.blockClose();
    } else {
      this.sb += this.indent() + 'item(' + this.editContainerHead(item.content);
      const anno = changeAnno(item.changeInfo);
      if (anno) this.sb += ', ' + anno;
      this.sb += ')\n';
    }
  }

  // ---- Table ----

  private appendTable(table: TableEditArea): void {
    const cols = table.columnsWidthPercent?.length ? `cols=[${table.columnsWidthPercent.map((c) => c + '%').join(', ')}]` : undefined;
    this.blockOpen('table', `width=${table.tableWidthPercent}%`, cols, changeAnno(table.changeInfo));
    for (const row of table.cells) this.appendTableRow(row);
    this.blockClose();
  }

  private appendTableRow(row: EditorContent[]): void {
    this.sb += this.indent() + 'row { ';
    row.forEach((cell, i) => {
      if (i > 0) this.sb += ' | ';
      this.appendCell(cell);
    });
    this.sb += ' }\n';
  }

  private appendCell(cell: EditorContent): void {
    const isSimple = cell.areas.length === 1 && cell.areas[0].kind === 'text';
    const anno = this.firstAreaChangeAnno(cell);
    if (isSimple) {
      this.sb += 'cell(' + this.editContainerHead(cell);
      if (anno) this.sb += ', ' + anno;
      this.sb += ')';
    } else {
      // wie im Original: blockOpen setzt die Einrückung mitten in die row-Zeile
      this.blockOpen('cell', this.editContainerHead(cell), anno);
      this.appendEditContainerTail(cell, 1);
      this.blockClose();
    }
  }

  // ---- Image ----

  private appendImage(image: ImageArea): void {
    const anno = changeAnno(image.changeInfo);
    this.sb += `${this.indent()}image(scale=${formatScale(image.individualScalePercent)}%, type=${imageTypeOf(image)}`;
    if (anno) this.sb += ', ' + anno;
    this.sb += ')';
    if (image.kind === 'plantuml' && image.backupSource !== undefined) {
      // The source is not indented, because everything between the backticks is the source.
      const changeset = image.backupChangeset ?? 'yellow';
      this.sb += ' {\n';
      this.sb += this.indent() + '    `' + image.source + '`,\n';
      this.sb += this.indent() + '    backup=(' + changeset + ', `' + image.backupSource + '`)\n';
      this.sb += this.indent() + '}\n';
    } else {
      this.sb += ' { ' + imageContentOf(image) + ' }\n';
    }
  }

  // ---- Steps ----

  private appendSteps(seq: StepSequence | undefined, idToNum: IdToNum): void {
    if (!seq) return;
    for (const step of seq.steps) this.appendStep(step, idToNum);
  }

  private appendStep(step: Step, idToNum: IdToNum): void {
    switch (step.kind) {
      case 'break':
        return this.appendLeafStep('break', step);
      case 'doWhile':
        return this.appendLoopStep('doWhile', step.loopSequence, step, idToNum, false, `barWidth=${step.barWidth}`);
      case 'while':
        return this.appendLoopStep('while', step.loopSequence, step, idToNum, true, `barWidth=${step.barWidth}`);
      case 'ifElse':
        return this.appendIfElseStep(step, idToNum);
      case 'if':
        return this.appendIfStep(step, idToNum);
      case 'case':
        return this.appendCaseStep(step, idToNum);
      case 'subsequence':
        return this.appendSubsequenceStep(step, idToNum);
      case 'source':
        return this.appendSourceStep(step);
      default:
        return this.appendLeafStep('simple', step);
    }
  }

  private appendSourceStep(step: SourceStep): void {
    const cs = step.changeInfo?.changeset ?? 'yellow';
    const targetParam = step.sourceStepId !== undefined ? `sourceStep=${normalizeId(step.sourceStepId)}` : undefined;
    const params = [stepNum(step), normalizeId(step.id), this.editContainerHead(step.content), cs, targetParam, decoParam(step), shadeParam(step), tagsParam(step)];
    if (step.content.areas.length > 1) {
      this.blockOpen('source', ...params);
      this.appendEditContainerTail(step.content, 1);
      this.blockClose();
    } else {
      this.block('source', ...params);
    }
  }

  private stepParams(step: Step, ...extra: (string | undefined)[]): (string | undefined)[] {
    return [
      stepNum(step),
      normalizeId(step.id),
      this.editContainerHead(step.content),
      ...extra,
      changeAnno(step.changeInfo, step.sourceStepId),
      decoParam(step),
      shadeParam(step),
      tagsParam(step),
    ];
  }

  private appendLeafStep(keyword: string, step: Step): void {
    if (step.content.areas.length > 1) {
      this.blockOpen(keyword, ...this.stepParams(step));
      this.appendEditContainerTail(step.content, 1);
      this.blockClose();
    } else {
      this.block(keyword, ...this.stepParams(step));
    }
  }

  private appendLoopStep(
    keyword: string,
    loopSeq: StepSequence,
    step: Step & { collapsed: boolean },
    idToNum: IdToNum,
    withCatch: boolean,
    extraParam: string,
  ): void {
    this.blockOpen(keyword, ...this.stepParams(step, extraParam, collapsedParam(step.collapsed)));
    this.appendEditContainerTail(step.content, 1);
    this.appendSteps(loopSeq, idToNum);
    if (withCatch) this.appendCatchArea(loopSeq.catchArea, idToNum);
    this.blockClose();
  }

  private appendIfElseStep(step: IfElseStep, idToNum: IdToNum): void {
    this.blockOpen('ifElse', ...this.stepParams(step, `ifRatio=${formatFloat2(step.ifWidthRatio * 100)}%`, collapsedParam(step.collapsed)));
    this.appendEditContainerTail(step.content, 1);
    this.appendBranch('if_branch', step.ifSequence, idToNum, true);
    this.appendBranch('else_branch', step.elseSequence, idToNum, true);
    this.blockClose();
  }

  private appendIfStep(step: IfStep, idToNum: IdToNum): void {
    this.blockOpen('if', ...this.stepParams(step, `emptyWidth=${step.emptyWidth}`, collapsedParam(step.collapsed)));
    this.appendEditContainerTail(step.content, 1);
    this.appendBranch('if_branch', step.ifSequence, idToNum, true);
    this.blockClose();
  }

  private appendCaseStep(step: CaseStep, idToNum: IdToNum): void {
    const cols = step.columnWidthRatios.length
      ? `cols=[${step.columnWidthRatios.map((r) => formatFloat2(r * 100) + '%').join(', ')}]`
      : undefined;
    this.blockOpen('case', ...this.stepParams(step, cols, collapsedParam(step.collapsed)));
    this.appendEditContainerTail(step.content, 1);
    this.appendBranch('default_branch', step.defaultSequence, idToNum, false);
    for (const c of step.caseSequences) this.appendBranch('case_branch', c, idToNum, false);
    this.blockClose();
  }

  private appendSubsequenceStep(step: SubsequenceStep, idToNum: IdToNum): void {
    this.blockOpen('subsequence', ...this.stepParams(step, step.flatNumbering ? 'flat=true' : undefined, collapsedParam(step.collapsed)));
    this.appendEditContainerTail(step.content, 1);
    this.appendSteps(step.subsequence, idToNum);
    this.appendCatchArea(step.subsequence.catchArea, idToNum);
    this.blockClose();
  }

  private appendBranch(keyword: string, branch: BranchSequence | undefined, idToNum: IdToNum, withCatch: boolean): void {
    if (!branch) return;
    this.blockOpen(keyword, this.editContainerHead(branch.heading), changeAnno(branch.changeInfo));
    this.appendEditContainerTail(branch.heading, 1);
    this.appendSteps(branch, idToNum);
    if (withCatch) this.appendCatchArea(branch.catchArea, idToNum);
    this.blockClose();
  }

  // ---- Catch area ----

  private appendCatchArea(catchArea: CatchArea | undefined, idToNum: IdToNum): void {
    if (!catchArea || catchArea.catchSequences.length === 0) return;
    const cols = catchArea.sequencesWidthPercent?.length
      ? `cols=[${catchArea.sequencesWidthPercent.map((c) => c + '%').join(', ')}]`
      : undefined;
    const params = [catchArea.collapsed ? 'collapsed=true' : undefined, cols].filter((p) => p !== undefined).join(', ');
    this.sb += this.indent() + 'catchArea';
    if (params) this.sb += '(' + params + ')';
    this.sb += ' {\n';
    this.indentionLevel++;
    for (const catchSeq of catchArea.catchSequences) {
      const breakStepNum = idToNum.get(catchSeq.id) ?? '?';
      const headingWidth = catchSeq.headingRightBarWidth !== 18 ? `headingWidth=${catchSeq.headingRightBarWidth}` : undefined;
      this.blockOpen('catch', breakStepNum, this.editContainerHead(catchSeq.heading), changeAnno(catchSeq.changeInfo), headingWidth);
      this.appendEditContainerTail(catchSeq.heading, 1);
      for (const coCatch of catchSeq.coCatches) {
        const coCatchNum = idToNum.get(coCatch.breakStepId) ?? '?';
        this.block('coCatch', coCatchNum, this.editContainerHead(coCatch.heading), changeAnno(coCatch.changeInfo));
      }
      this.appendSteps(catchSeq, idToNum);
      this.blockClose();
    }
    this.indentionLevel--;
    this.sb += this.indent() + '}\n';
  }

  // ---- Blöcke ----

  private blockBegin(blockType: string, ...parameters: (string | undefined)[]): void {
    const p = parameters.filter((x) => x !== undefined).join(', ');
    this.sb += this.indent() + blockType;
    if (p) this.sb += '(' + p + ')';
  }

  private blockOpen(blockType: string, ...parameters: (string | undefined)[]): void {
    this.blockBegin(blockType, ...parameters);
    this.sb += ' {\n';
    this.indentionLevel++;
  }

  private blockClose(): void {
    this.indentionLevel--;
    this.sb += this.indent() + '}\n';
  }

  private block(blockType: string, ...parameters: (string | undefined)[]): void {
    this.blockBegin(blockType, ...parameters);
    this.sb += ';\n';
  }
}

// ---- Hilfsfunktionen ----

/** The XML way to write a backtick, which would end the source in the model file. */
const BACKTICK_CHARACTER_REFERENCE = '&#96;';

function hasContent(container: EditorContent | undefined): container is EditorContent {
  return container !== undefined && container.areas.length > 0;
}

/** String.trim() von Java: entfernt alle Zeichen <= U+0020 an beiden Enden, aber kein NBSP o. Ä. */
function javaTrim(s: string): string {
  let start = 0;
  let end = s.length;
  while (start < end && s.charCodeAt(start) <= 0x20) start++;
  while (end > start && s.charCodeAt(end - 1) <= 0x20) end--;
  return s.substring(start, end);
}

function extractBodyHtml(text: string | undefined): string {
  if (text === undefined) return '';
  const m = /<body>([\s\S]*?)<\/body>/.exec(text);
  return javaTrim(m ? m[1] : text);
}

function escapeBackticks(text: string | undefined): string {
  return text === undefined ? '' : text.replaceAll('`', "'");
}

const CHANGE_TYPE_NAMES = {
  Hinzugefuegt: 'added',
  Geloescht: 'removed',
  Quellschritt: 'source',
  Zielschritt: 'target',
} as const;

function changeAnno(info: ChangeInfo | undefined, sourceStepId?: string): string | undefined {
  if (!info) return undefined;
  let result = `change=(${CHANGE_TYPE_NAMES[info.changetype]}, ${info.changeset ?? 'yellow'}`;
  if (sourceStepId !== undefined && info.changetype === 'Zielschritt') result += `, sourceStep=${normalizeId(sourceStepId)}`;
  return result + ')';
}

function decoParam(step: Step): string | undefined {
  return step.decorationStyle === 'None' ? undefined : `deco=${step.decorationStyle}`;
}

/** ReadWriteColor.toHTMLColor für eine deckende Farbe */
function shadeParam(step: Step): string | undefined {
  return step.shade === undefined ? undefined : 'shade=#' + (step.shade & 0xffffff).toString(16).padStart(6, '0');
}

function tagsParam(step: Step): string | undefined {
  if (step.tags.length === 0) return undefined;
  const refs = step.tags.map((t) => {
    const ft = t.freetext ? ', `' + escapeBackticks(t.freetext) + '`' : '';
    return '(`' + escapeBackticks(t.configName) + '`' + ft + ')';
  });
  return `tags=[${refs.join(', ')}]`;
}

function collapsedParam(collapsed: boolean): string | undefined {
  return collapsed ? 'collapsed=true' : undefined;
}

function stepNum(step: Step): string {
  return step.stepNumber ?? '?';
}

/** ReadWriteColor.toModelColor: #rrggbb, bei Transparenz #rrggbbaa */
export function toModelColor(argb: number): string {
  const rgb = '#' + (argb & 0xffffff).toString(16).padStart(6, '0');
  const alpha = (argb >>> 24) & 0xff;
  return alpha === 255 ? rgb : rgb + alpha.toString(16).padStart(2, '0');
}

/** String.format(Locale.US, "%.2f", v) */
function formatFloat2(v: number): string {
  return (Math.round(v * 100 + Number.EPSILON * Math.sign(v)) / 100).toFixed(2);
}

/** Skalierung wie im Original: auf 2 Nachkommastellen, Nullen am Ende entfernt */
function formatScale(scale: number): string {
  const rounded = Math.round(scale * 10000) / 100;
  return rounded.toFixed(2).replace(/\.?0+$/, '');
}

function imageTypeOf(image: ImageArea): string {
  if (image.kind === 'plantuml') return 'plantuml';
  if (image.kind === 'svg') return 'svg';
  return image.imageType ?? 'png';
}

function imageContentOf(image: ImageArea): string {
  if (image.kind === 'plantuml') return '`' + image.source + '`';
  if (image.kind === 'svg') return '`' + image.source.replaceAll('`', BACKTICK_CHARACTER_REFERENCE) + '`';
  return '[base64:' + image.imageData + ']';
}
